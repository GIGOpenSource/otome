_current = contextvars.ContextVar("otome_lang", default="zh-Hans")


def canonical(raw):
    text = str(raw or "").strip().replace("_", "-")
    if not text:
        return ""
    lowered = text.lower()
    if lowered in ("zh-hant", "zh-tw", "zh-hk", "zh-mo") or "hant" in lowered:
        return "zh-Hant"
    if lowered.startswith("zh"):
        return "zh-Hans"
    primary = lowered.split("-", 1)[0]
    return _PRIMARY.get(primary, "")


def _accept_lang(request):
    header = request.headers.get("Accept-Language") or ""
    for part in header.split(","):
        found = canonical(part.split(";", 1)[0].strip())
        if found:
            return found
    return ""


def resolve_lang(request):
    query = canonical(request.GET.get("lang"))
    if query:
        return query
    explicit = canonical(request.headers.get("X-Otome-Lang") or request.META.get("HTTP_X_OTOME_LANG") or "")
    if explicit:
        return explicit
    cookie = canonical(request.COOKIES.get("otome_lang"))
    if cookie:
        return cookie
    return _accept_lang(request) or "zh-Hans"


def activate(code):
    lang = canonical(code) or "zh-Hans"
    _current.set(lang)
    return lang


def current_lang():
    return _current.get()


def lang_meta(code=None):
    return _BY_CODE.get(code or current_lang()) or _BY_CODE["zh-Hans"]


def lang_name(code):
    return lang_meta(code)["name"]


def clean_lang(raw):
    """空值用简体中文。无法识别时返回 None，调用方应拒绝保存。"""
    text = str(raw or "").strip()
    if not text:
        return "zh-Hans"
    return canonical(text) or None


def filter_lang(queryset, raw, field="lang"):
    text = str(raw or "").strip()
    if not text:
        return queryset
    code = canonical(text)
    if not code:
        return queryset.none()
    return queryset.filter(**{field: code})


def tr(text):
    if not isinstance(text, str) or not text or text == "success":
        return text
    lang = current_lang()
    if lang == "zh-Hans":
        return text
    pack = PACKS.get(lang) or {}
    if text in pack:
        return pack[text]
    english = _EN.get(text)
    if english:
        return english
    return text


def translate_data(value):
    if isinstance(value, str):
        return tr(value)
    if isinstance(value, list):
        return [translate_data(item) for item in value]
    if isinstance(value, dict):
        return {key: translate_data(item) for key, item in value.items()}
    return value
